// =============================================================================
// THE CONTRACT between this frontend and the backend.
// The backend returns/accepts exactly these shapes. Change them together.
// =============================================================================

export type ThemeId = "cancer" | "diabetes" | "cardiac" | "operations" | "icu";

export interface Theme {
  id: ThemeId;
  /** 3-letter code used in registration IDs, e.g. "DIA" → EPOCH-DIA-07 */
  code: string;
  name: string;
  blurb: string;
  /** always 5 for EPOCH */
  capacity: number;
  /** teams that have SUBMITTED for this theme (slots are only locked on submit) */
  taken: number;
}

export type Semester = 1 | 3 | 5 | 7;
export const SEMESTERS: readonly Semester[] = [1, 3, 5, 7];

export interface Member {
  fullName: string;
  /** stored upper-case, no spaces, e.g. "1DS23CD045" */
  usn: string;
  /** 10 digits, no country code */
  phone: string;
  semester: Semester;
  /** exactly one member per team is the lead (Member 01 in the form) */
  isLead: boolean;
}

/** What the frontend sends on final submit. */
export interface TeamInput {
  teamName: string;
  themeId: ThemeId;
  /** 3 or 4 members, exactly one with isLead = true */
  members: Member[];
}

/** What the backend returns once a team is locked in. */
export interface Registration {
  /** e.g. "EPOCH-DIA-07" — generated by the backend */
  id: string;
  teamName: string;
  themeId: ThemeId;
  themeName: string;
  members: Member[];
  /** ISO timestamp */
  createdAt: string;
}

export type ApiErrorCode =
  | "THEME_FULL" //            the chosen theme filled up before this submit
  | "DUPLICATE_USN" //         a USN is already in another team (see `usns`)
  | "REGISTRATIONS_CLOSED" //  all 25 slots are gone
  | "VALIDATION" //            server-side validation failed (see `message`)
  | "NETWORK"; //              request failed / timed out

export interface ApiError {
  code: ApiErrorCode;
  message: string;
  /** DUPLICATE_USN only: the USNs that are already registered */
  usns?: string[];
}

export type SubmitResult = { ok: true; registration: Registration } | { ok: false; error: ApiError };
